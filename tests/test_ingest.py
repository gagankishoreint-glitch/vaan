PDFS = Path("data/papers")


def _require_pdfs() -> None:
    """Skip is not an option for these tests.

    The PDFs are git-ignored, so a fresh clone has none of them. A `skipif` would
    then quietly reduce the corpus tests to zero on exactly the machine least
    likely to notice, and the suite would still report success. The corpus is the
    input to the ingest, so its absence is a failure to set up, not a reason to
    test nothing. The recovery is one command and is printed.
    """
    missing = [PDFS / m["file"] for m in PAPERS.values()
               if not (PDFS / m["file"]).is_file()]
    if missing:
        pytest.fail(
            "PDFs missing, so the corpus tests cannot run:\n  "
            + "\n  ".join(str(m) for m in missing)
            + "\n\nRestore the files named in data/papers/SHA256SUMS (committed), "
              "then verify:\n    (cd data/papers && sha256sum -c SHA256SUMS)\n"
              "See docs/P2_INGEST.md. These tests do not skip when the corpus is "
              "absent.",
            pytrace=False)


def ln(text, size=10.0, bold=False):
    return {"text": text, "size": size, "bold": bold, "bbox": None}


def page(n, lines):
    return {"page": n, "lines": lines}


# ------------------------------------------------------------------ text quality

def test_is_mostly_digits_on_real_table_rows():
    assert is_mostly_digits("41.29 7.7 1019 9.6 1018 1.5 1020 2.0 1019")
    assert is_mostly_digits("1.0 . 1020 2.3 . 1019")
    assert not is_mostly_digits("The encoder is composed of a stack of 6 layers.")
    assert not is_mostly_digits("short 1 2 3")


def test_digit_ratio_bounds():
    assert digit_ratio("") == 0.0
    assert digit_ratio("abc") == 0.0
    assert digit_ratio("123") == 1.0
    assert 0 < digit_ratio("a1b2") < 1


def test_figure_junk_detects_one_char_per_line():
    """hnet page 3 extracts as one character per line (a TikZ figure)."""
    lines = ["n", "d", "o", "f", "t", "o", "k", "e", "s", "a", "b", "c"]
    assert looks_like_figure_junk(lines)


def test_figure_junk_false_positive_on_prose():
    lines = ["The encoder is composed of a stack of six identical layers.",
             "Each layer has two sub-layers."]
    assert not looks_like_figure_junk(lines)


def test_figure_junk_needs_enough_lines():
    assert not looks_like_figure_junk(["a", "b"])


