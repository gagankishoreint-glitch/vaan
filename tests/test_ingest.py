def test_embedded_caption_is_flagged_not_hidden():
    """Measured on the real corpus: 50/449 'ok' chunks contained a caption.
    They stay in the corpus (retrieval must cope) but are labelled."""
    from relay.ingest import has_embedded_caption
    assert has_embedded_caption("text ... Table 1: Maximum path lengths ... more")
    assert has_embedded_caption("Figure 2: The Transformer architecture")
    assert not has_embedded_caption("We tabulate the results in a table of numbers.")
    assert not has_embedded_caption("Figure it out.")


