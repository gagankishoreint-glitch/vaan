# --------------------------------------------------------- section assembly rules

def test_split_heading_across_two_lines():
    """attention: '3.1' and 'Encoder and Decoder Stacks' are separate lines."""
    pages = [page(1, [ln("Intro text " * 30), ln("3.1", size=10, bold=True),
                      ln("Encoder and Decoder Stacks", size=10, bold=True),
                      ln("Body " * 40)])]
    secs, _ = build_sections(pages, "attention")
    assert any(s.number == "3.1" and s.title == "Encoder and Decoder Stacks"
               for s in secs), [s.path for s in secs]


def test_size_only_heading_not_bold():
    """moshi/hnet headings are 12pt and NOT bold."""
    pages = [page(1, [ln("Body text here " * 20), ln("2.2", size=12.0),
                      ln("Dynamic Chunking (DC)", size=12.0),
                      ln("More body " * 30)])]
    secs, _ = build_sections(pages, "hnet")
    assert any("Dynamic Chunking" in s.title for s in secs), [s.path for s in secs]


def test_body_sized_numbered_heading_accepted_by_sequence():
    """moshi's sub-headings are body-sized AND not bold: only numbering saves them."""
    pages = [page(1, [ln("3 Model", size=10.9), ln("body " * 40),
                      ln("3.1 Overview", size=10.9), ln("body " * 40)])]
    secs, _ = build_sections(pages, "moshi")
    paths = [s.path for s in secs]
    assert any("3.1 Overview" == p for p in paths), paths


def test_author_names_are_not_sections():
    """The Unicode asterisk (U+2217) broke an ASCII-only rule once."""
    pages = [page(1, [ln("Ashish Vaswani\u2217", size=10.0, bold=True),
                      ln("Google Brain"), ln("Abstract"),
                      ln("We propose " * 40)])]
    secs, _ = build_sections(pages, "attention")
    titles = [s.title for s in secs]
    assert "Ashish Vaswani\u2217" not in titles
    assert "Google Brain" not in titles
    assert "Abstract" in titles


def test_footnote_urls_are_not_sections():
    pages = [page(1, [ln("1 Introduction"), ln("body " * 30),
                      ln("4 https://openai.com/index/chatgpt")])]
    secs, _ = build_sections(pages, "moshi")
    assert all("http" not in s.title for s in secs)


def test_sentence_with_leading_number_is_not_a_section():
    pages = [page(1, [ln("1 Introduction"), ln("body " * 30),
                      ln("3.4 describes this architecture.")])]
    secs, _ = build_sections(pages, "moshi")
    assert all(not s.title.endswith(".") for s in secs)


def test_measurement_is_not_a_section():
    pages = [page(1, [ln("1 Introduction"), ln("body " * 30), ln("12.5 Hz"),
                      ln("5 \u00b7 10-5")])]
    secs, _ = build_sections(pages, "attention")
    assert all("Hz" not in s.title for s in secs)
    assert all("\u00b7" not in s.title for s in secs)


def test_figure_junk_page_is_skipped_but_counted():
    lines = [ln("1 Introduction")] + [ln(c) for c in "nndoftokesabc"] + [ln("body " * 20)]
    pages = [page(1, lines)]
    secs, reports = build_sections(pages, "hnet")
    assert reports[0].figure_junk is True
    assert all(not s.text.strip().startswith("n") or len(s.text) > 20 for s in secs)


# --------------------------------------------------------------------- chunking

def test_chunk_ids_are_deterministic_and_sectioned():
    sec = Section(paper="attention", number="3.2", title="Attention", page=4,
                  text="word " * 400)
    a = split_section(sec, 900, 150, "attn-v7")
    b = split_section(sec, 900, 150, "attn-v7")
    assert [r.chunk_id for r in a] == [r.chunk_id for r in b]
    assert a[0].chunk_id == "attn-v7:s3.2:c0000"


def test_chunks_respect_size_and_overlap():
    sec = Section(paper="p", number="1", title="T", page=1, text="a" * 5000)
    recs = split_section(sec, 900, 150, "p")
    assert all(len(r.chunk.text) <= 900 for r in recs)
    # overlap means consecutive chunks share the tail/head
    assert len(recs) > 5000 / 900


def test_no_chunk_starts_or_ends_mid_word():
    """H2: a quote spanning a boundary must be a verbatim substring of the chunk
    that contains it. That only holds if boundaries land between words.

    The weaker 'every word appears somewhere' assertion is useless here: even a
    splitter that hard-cuts mid-word loses no characters, so it passes (verified).
    """
    body = " ".join(f"word{i:04d}" for i in range(800))
    words = set(body.split())
    sec = Section(paper="p", number="1", title="T", page=1, text=body)
    recs = split_section(sec, 900, 150, "p")
    for r in recs:
        toks = r.chunk.text.split()
        assert toks[0] in words, f"{r.chunk_id} starts mid-word: {toks[0]!r}"
        assert toks[-1] in words, f"{r.chunk_id} ends mid-word: {toks[-1]!r}"


def test_adjacent_chunks_overlap_by_a_whole_word():
    """Overlap must carry real words across, not a partial token."""
    body = " ".join(f"w{i:03d}" for i in range(400))
    sec = Section(paper="p", number="1", title="T", page=1, text=body)
    recs = split_section(sec, 300, 60, "p")
    a, b = recs[0].chunk.text, recs[1].chunk.text
    shared = set(a.split()) & set(b.split())
    assert len(shared) >= 3, f"only {len(shared)} words shared across the boundary"


